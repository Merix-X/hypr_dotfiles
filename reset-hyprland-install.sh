#!/usr/bin/env bash
set -Eeuo pipefail

# Reversible reset after copying personal configs into their live locations.
# Run as the normal desktop user, NOT with sudo.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
DEFAULT_LUA="$SCRIPT_DIR/hyprland.lua"

if [[ ! -f "$DEFAULT_LUA" ]]; then
    printf 'ERROR: Missing %s\nKeep hyprland.lua next to this script.\n' "$DEFAULT_LUA" >&2
    exit 1
fi

if [[ "${EUID}" -eq 0 ]]; then
    printf 'Run this script as your normal user, without sudo.\n' >&2
    exit 1
fi

CONFIG_HOME="$HOME/.config"
if [[ -n "${XDG_CONFIG_HOME:-}" && "$XDG_CONFIG_HOME" != "$CONFIG_HOME" ]]; then
    printf 'WARNING: XDG_CONFIG_HOME=%s differs from ~/.config; this script reverses the exact paths used by your cp commands.
' "$XDG_CONFIG_HOME" >&2
fi
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="$HOME/.local/state/hyprland-reset-backup-$STAMP"
SDDM_CONF="/usr/share/sddm/themes/sugar-candy/theme.conf"

cat <<PROMPT
This will remove the listed configurations from their active locations and
keep their current contents in this backup folder:
  $BACKUP

The Hyprland Lua config will be replaced by the upstream Hyprland 0.55.0
example with the autogenerated-warning marker enabled.
PROMPT
read -r -p 'Continue? [y/N] ' answer
[[ "$answer" =~ ^[Yy]$ ]] || { echo 'Cancelled.'; exit 0; }

mkdir -p "$BACKUP/config" "$BACKUP/home"

# Move whole configuration directories out of the live XDG config directory.
# They remain available in the backup if anything else was stored in them.
for name in hypr waybar dunst kitty gtk rofi starship; do
    src="$CONFIG_HOME/$name"
    if [[ -e "$src" || -L "$src" ]]; then
        mv -- "$src" "$BACKUP/config/$name"
        printf 'Moved %s to backup.\n' "$src"
    fi
done

# Remove the copied shell config from its active path. Prefer the system skeleton
# template if present; otherwise leave .zshrc absent so Zsh can offer its setup wizard.
if [[ -e "$HOME/.zshrc" || -L "$HOME/.zshrc" ]]; then
    mv -- "$HOME/.zshrc" "$BACKUP/home/.zshrc"
    printf 'Moved ~/.zshrc to backup.\n'
fi
if [[ -f /etc/skel/.zshrc ]]; then
    cp -a /etc/skel/.zshrc "$HOME/.zshrc"
    printf 'Restored /etc/skel/.zshrc.\n'
else
    printf 'No /etc/skel/.zshrc found; ~/.zshrc remains absent.\n'
fi

# Record whether pacman knows which package originally provided the SDDM file.
SDDM_OWNER=''
if command -v pacman >/dev/null 2>&1 && [[ -e "$SDDM_CONF" ]]; then
    SDDM_OWNER="$(pacman -Qqo -- "$SDDM_CONF" 2>/dev/null || true)"
fi

if [[ -e "$SDDM_CONF" || -L "$SDDM_CONF" ]]; then
    mkdir -p "$BACKUP/system"
    sudo cp -a -- "$SDDM_CONF" "$BACKUP/system/sugar-candy-theme.conf.current-custom-copy"
    sudo rm -f -- "$SDDM_CONF"
    printf 'Removed the copied SDDM theme.conf from its active path.\n'
fi

# If the file belongs to a repository package, reinstall that package to restore
# its packaged original. For AUR packages, try the installed helper if available.
if [[ -n "$SDDM_OWNER" ]]; then
    if pacman -Si "$SDDM_OWNER" >/dev/null 2>&1; then
        printf 'Restoring the SDDM file from repository package %s...\n' "$SDDM_OWNER"
        sudo pacman -S --noconfirm "$SDDM_OWNER" || printf 'WARNING: package reinstall failed; see notes below.\n' >&2
    elif command -v paru >/dev/null 2>&1; then
        printf 'Trying to rebuild/reinstall AUR package %s with paru...\n' "$SDDM_OWNER"
        paru -S --rebuild --noconfirm "$SDDM_OWNER" || printf 'WARNING: AUR restore failed; see notes below.\n' >&2
    elif command -v yay >/dev/null 2>&1; then
        printf 'Trying to rebuild/reinstall AUR package %s with yay...\n' "$SDDM_OWNER"
        yay -S --rebuild --noconfirm "$SDDM_OWNER" || printf 'WARNING: AUR restore failed; see notes below.\n' >&2
    else
        printf 'WARNING: pacman says %s owns the SDDM file, but the package is not in configured repositories and no paru/yay was found. Reinstall %s manually to restore its packaged theme.conf.\n' "$SDDM_OWNER" "$SDDM_OWNER" >&2
    fi
elif [[ -d /usr/share/sddm/themes/sugar-candy ]]; then
    # Only remove the directory if it is now empty; do not remove installed theme assets.
    sudo rmdir --ignore-fail-on-non-empty /usr/share/sddm/themes/sugar-candy 2>/dev/null || true
    printf 'No package owner could be detected for the SDDM file. If Sugar-Candy was installed as a package, reinstall that package to restore its original theme.conf.\n'
fi

# Put the default Hyprland Lua config in the live config location.
mkdir -p "$CONFIG_HOME/hypr"
install -m 0644 -- "$DEFAULT_LUA" "$CONFIG_HOME/hypr/hyprland.lua"
printf 'Installed default-style Lua config at %s/hyprland.lua.\n' "$CONFIG_HOME/hypr"

# Apply it now if run inside an active Hyprland session.
if [[ "${HYPRLAND_INSTANCE_SIGNATURE:-}" != '' ]] && command -v hyprctl >/dev/null 2>&1; then
    hyprctl reload || printf 'Could not reload the running session; log out and back into Hyprland.\n' >&2
fi

cat <<DONE

Reset finished.
Backup: $BACKUP
The backup is intentionally retained. Once you have verified the desktop and
SDDM theme, you can delete that folder manually if you no longer need it.
DONE
